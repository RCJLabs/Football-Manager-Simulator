export function slugify(name) {
  return name.normalize('NFD').replace(/[̀-ͯ]/g, '').toLowerCase().replace(/['".]/g, '').replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
}

function expand(raw) {
  const out = [];
  for (const [pos, rows] of Object.entries(raw)) {
    const attrs = POSITIONS[pos].attrs;
    for (const row of rows) {
      const [name, season, team, ...vals] = row;
      const r = {};
      attrs.forEach((a, i) => { r[a] = vals[i]; });
      out.push({ id: `${slugify(name)}-${season}`, name, pos, season, team, r });
    }
  }
  return out;
}

